-- Schema completo do Soulie para um banco PostgreSQL vazio.
-- Cria as tabelas já no formato final, incluindo o contrato do app.
--
-- Se a API sobe com Flyway, não execute este arquivo no mesmo banco:
-- o Flyway aplica db.migrations/V1 até V12 e chega no mesmo resultado.

CREATE TABLE users
(
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                    VARCHAR(100) NOT NULL,
    email                   VARCHAR(150) NOT NULL UNIQUE,
    password                VARCHAR(255) NOT NULL,
    points                  INTEGER      NOT NULL DEFAULT 0,
    active                  BOOLEAN      NOT NULL DEFAULT TRUE,
    handle                  VARCHAR(80) UNIQUE,
    avatar_url              VARCHAR(500),
    created_at              TIMESTAMP    NOT NULL DEFAULT NOW(),
    streak_days             INTEGER      NOT NULL DEFAULT 0,
    last_activity_date      DATE,
    co2_saved_kg            DOUBLE PRECISION NOT NULL DEFAULT 0,
    water_saved_liters      DOUBLE PRECISION NOT NULL DEFAULT 0,
    notifications_enabled   BOOLEAN      NOT NULL DEFAULT TRUE,
    email_weekly_digest     BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE avatars
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL UNIQUE,
    name            VARCHAR(100) NOT NULL,
    level           INTEGER      NOT NULL DEFAULT 0,
    humor           VARCHAR(50)  NOT NULL,
    plant_type      VARCHAR(50)  NOT NULL DEFAULT 'IPE_AMARELO',
    flower_type     VARCHAR(30)  NOT NULL DEFAULT 'GIRASSOL',
    xp              INTEGER      NOT NULL DEFAULT 0,
    last_watered_at TIMESTAMP,
    CONSTRAINT fk_avatars_user_id FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE actions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    description VARCHAR(255) NOT NULL,
    points      INTEGER      NOT NULL
);

CREATE TABLE missions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id   BIGINT       NOT NULL,
    avatar_id   BIGINT       NOT NULL,
    description VARCHAR(500) NOT NULL,
    CONSTRAINT fk_missions_action_id FOREIGN KEY (action_id) REFERENCES actions (id),
    CONSTRAINT fk_missions_avatar_id FOREIGN KEY (avatar_id) REFERENCES avatars (id)
);

CREATE TABLE evidences
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    mission_id BIGINT       NOT NULL,
    image      VARCHAR(500) NOT NULL,
    CONSTRAINT fk_evidences_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_evidences_mission_id FOREIGN KEY (mission_id) REFERENCES missions (id)
);

CREATE TABLE validations
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evidence_id       BIGINT  NOT NULL UNIQUE,
    result_validation INTEGER NOT NULL,
    CONSTRAINT fk_validations_evidence_id FOREIGN KEY (evidence_id) REFERENCES evidences (id)
);

CREATE TABLE history_points
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id     BIGINT  NOT NULL,
    user_id       BIGINT  NOT NULL,
    date          DATE    NOT NULL,
    points_earned INTEGER NOT NULL,
    CONSTRAINT fk_history_points_action_id FOREIGN KEY (action_id) REFERENCES actions (id),
    CONSTRAINT fk_history_points_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT check_history_points_earned CHECK (points_earned >= 0),
    CONSTRAINT uq_history_points_action_user_date UNIQUE (action_id, user_id, date)
);

CREATE TABLE rewards
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL,
    benefits     VARCHAR(500) NOT NULL,
    points_spent INTEGER      NOT NULL,
    CONSTRAINT fk_rewards_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT check_rewards_points_spent CHECK (points_spent > 0)
);

CREATE TABLE interactions
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id   BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    kind        VARCHAR(20) NOT NULL DEFAULT 'NUDGE',
    CONSTRAINT fk_interactions_sender_id FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT fk_interactions_receiver_id FOREIGN KEY (receiver_id) REFERENCES users (id),
    CONSTRAINT check_interactions_different_users CHECK (sender_id <> receiver_id)
);

CREATE TABLE gardens
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    invite_code VARCHAR(12)  NOT NULL,
    CONSTRAINT uq_gardens_invite_code UNIQUE (invite_code)
);

CREATE TABLE gardens_users
(
    garden_id BIGINT NOT NULL,
    user_id   BIGINT NOT NULL,
    PRIMARY KEY (garden_id, user_id),
    CONSTRAINT fk_garden_users_garden_id FOREIGN KEY (garden_id) REFERENCES gardens (id),
    CONSTRAINT fk_garden_users_user_id FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE daily_missions
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emoji              VARCHAR(16)  NOT NULL,
    name               VARCHAR(120) NOT NULL,
    tag                VARCHAR(40)  NOT NULL,
    description        VARCHAR(500) NOT NULL,
    xp                 INTEGER      NOT NULL,
    co2_saved_kg       DOUBLE PRECISION NOT NULL DEFAULT 0,
    water_saved_liters DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE user_mission_completions
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    mission_id   BIGINT NOT NULL,
    completed_on DATE   NOT NULL,
    completed_at TIMESTAMP NOT NULL,
    image_name   VARCHAR(255),
    CONSTRAINT fk_user_mission_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_mission_mission FOREIGN KEY (mission_id) REFERENCES daily_missions (id),
    CONSTRAINT uq_user_mission_day UNIQUE (user_id, mission_id, completed_on)
);

CREATE TABLE achievements
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    icon        VARCHAR(40)  NOT NULL,
    color       VARCHAR(20)  NOT NULL,
    category    VARCHAR(40)  NOT NULL,
    xp_reward   INTEGER      NOT NULL,
    target      INTEGER      NOT NULL,
    metric      VARCHAR(30)  NOT NULL,
    metric_key  VARCHAR(40)
);

CREATE TABLE user_achievements
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT  NOT NULL,
    achievement_id BIGINT  NOT NULL,
    progress       INTEGER NOT NULL DEFAULT 0,
    unlocked       BOOLEAN NOT NULL DEFAULT FALSE,
    unlocked_at    TIMESTAMP,
    CONSTRAINT fk_user_achievement_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_user_achievement_achievement FOREIGN KEY (achievement_id) REFERENCES achievements (id),
    CONSTRAINT uq_user_achievement UNIQUE (user_id, achievement_id)
);

CREATE TABLE user_activities
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    emoji      VARCHAR(16)  NOT NULL,
    label      VARCHAR(180) NOT NULL,
    xp         INTEGER      NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_user_activity_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE feed_posts
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL,
    text         VARCHAR(2000) NOT NULL,
    image_uri    VARCHAR(2000),
    mission_name VARCHAR(120),
    xp           INTEGER,
    garden_id    BIGINT,
    created_at   TIMESTAMP     NOT NULL,
    CONSTRAINT fk_feed_post_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_feed_post_garden FOREIGN KEY (garden_id) REFERENCES gardens (id) ON DELETE SET NULL
);

CREATE TABLE feed_comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL,
    user_id    BIGINT        NOT NULL,
    text       VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    CONSTRAINT fk_feed_comment_post FOREIGN KEY (post_id) REFERENCES feed_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_feed_comment_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    title      VARCHAR(120) NOT NULL,
    body       VARCHAR(500) NOT NULL,
    read_at    TIMESTAMP,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE feed_likes
(
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_feed_like_post FOREIGN KEY (post_id) REFERENCES feed_posts (id),
    CONSTRAINT fk_feed_like_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uq_feed_like UNIQUE (post_id, user_id)
);

