-- Convite, feed do jardim, conversa, cutucada e notificação.

ALTER TABLE gardens
    ADD COLUMN invite_code VARCHAR(12);

UPDATE gardens
SET invite_code = upper(substr(md5(id::text), 1, 6))
WHERE invite_code IS NULL;

ALTER TABLE gardens
    ALTER COLUMN invite_code SET NOT NULL;

CREATE UNIQUE INDEX uq_gardens_invite_code ON gardens (invite_code);

ALTER TABLE feed_posts
    ADD COLUMN garden_id BIGINT;

ALTER TABLE feed_posts
    ADD CONSTRAINT fk_feed_post_garden FOREIGN KEY (garden_id) REFERENCES gardens (id) ON DELETE SET NULL;

CREATE TABLE feed_comments
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT        NOT NULL,
    user_id    BIGINT        NOT NULL,
    text       VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP     NOT NULL,
    CONSTRAINT fk_feed_comment_post FOREIGN KEY (post_id) REFERENCES feed_posts (id) ON DELETE CASCADE,
    CONSTRAINT fk_feed_comment_user FOREIGN KEY (user_id) REFERENCES users (id)
);

ALTER TABLE interactions
    ADD COLUMN created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'NUDGE';

CREATE TABLE notifications
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    title      VARCHAR(120) NOT NULL,
    body       VARCHAR(500) NOT NULL,
    read_at    TIMESTAMP,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notification_user FOREIGN KEY (user_id) REFERENCES users (id)
);
