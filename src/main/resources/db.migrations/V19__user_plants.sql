-- Coleção de plantas: cada tipo tem XP próprio. A escolhida no cadastro já nasce liberada.

CREATE TABLE user_plants
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id),
    plant_type    VARCHAR(40) NOT NULL,
    xp            INTEGER     NOT NULL DEFAULT 0,
    unlocked      BOOLEAN     NOT NULL DEFAULT FALSE,
    unlocked_at   TIMESTAMP,
    unlock_source VARCHAR(32),
    CONSTRAINT uq_user_plants UNIQUE (user_id, plant_type)
);

CREATE INDEX idx_user_plants_user ON user_plants (user_id);

INSERT INTO user_plants (user_id, plant_type, xp, unlocked, unlocked_at, unlock_source)
SELECT u.id,
       COALESCE(a.flower_type, 'IPE_AMARELO'),
       COALESCE(a.xp, 0),
       TRUE,
       NOW(),
       'STARTER'
FROM users u
         LEFT JOIN avatars a ON a.user_id = u.id
WHERE NOT EXISTS (
    SELECT 1 FROM user_plants p WHERE p.user_id = u.id AND p.plant_type = COALESCE(a.flower_type, 'IPE_AMARELO')
);
