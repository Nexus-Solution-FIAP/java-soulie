CREATE TABLE interactions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id   BIGINT NOT NULL,
    receiver_id BIGINT NOT NULL,
    CONSTRAINT fk_interactions_sender_id FOREIGN KEY (sender_id) REFERENCES users(id),
    CONSTRAINT fk_interactions_receiver_id FOREIGN KEY (receiver_id) REFERENCES users(id),
    CONSTRAINT check_interactions_different_users CHECK (sender_id <> receiver_id)
);
