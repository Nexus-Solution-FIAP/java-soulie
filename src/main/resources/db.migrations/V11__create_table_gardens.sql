CREATE TABLE gardens
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE gardens_users
(
    garden_id BIGINT NOT NULL,
    user_id   BIGINT NOT NULL,
    constraint fk_garden_users_garden_id foreign key (garden_id) references gardens (id),
    constraint fk_garden_users_user_id foreign key (user_id) references users (id)

);
