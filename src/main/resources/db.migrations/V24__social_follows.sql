-- Grafo social: seguir é unilateral, amizade é mútua.
--
-- Até aqui o "social" do projeto era inteiramente mediado pelo jardim: o
-- ranking lista membros do jardim, o feed é escopado por garden_id, e a
-- cutucada exige que o alvo esteja no mesmo jardim. O código já chamava essas
-- pessoas de amigos (NUDGES_PER_FRIEND_PER_DAY, "Lembra um amigo da sequência")
-- sem existir grafo social nenhum.
--
-- AMIZADE NÃO TEM TABELA. Ela é a propriedade derivada "existem os dois sentidos
-- do follow". Guardar amizade numa segunda tabela criaria um estado para manter
-- em sincronia com o follow, e os dois divergiriam no primeiro caminho de erro.

CREATE TABLE follows
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT    NOT NULL,
    followee_id BIGINT    NOT NULL,
    created_at  TIMESTAMP NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_follows_follower_id FOREIGN KEY (follower_id) REFERENCES users (id),
    CONSTRAINT fk_follows_followee_id FOREIGN KEY (followee_id) REFERENCES users (id),

    -- Seguir duas vezes não cria linha nova: o segundo POST é inócuo.
    CONSTRAINT uq_follows_pair UNIQUE (follower_id, followee_id),

    -- Ninguém segue a si mesmo. O validator da aplicação também barra, mas
    -- validação só no código é contornável por corrida — esta é a regra que
    -- não tem como escapar.
    CONSTRAINT check_follows_not_self CHECK (follower_id <> followee_id)
);

-- Os dois sentidos são consultados: "quem eu sigo" e "quem me segue". A
-- consulta de amizade mútua percorre os dois no mesmo EXISTS, e é a mais
-- chamada do grafo — ranking, feed e cutucada passam por ela.
CREATE INDEX idx_follows_follower_id ON follows (follower_id);
CREATE INDEX idx_follows_followee_id ON follows (followee_id);
