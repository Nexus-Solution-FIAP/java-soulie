CREATE TABLE history_points (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_id     BIGINT NOT NULL,
    user_id       BIGINT NOT NULL,
    date          DATE NOT NULL,
    points_earned INTEGER NOT NULL,
    CONSTRAINT fk_history_points_action_id FOREIGN KEY (action_id) REFERENCES actions(id),
    CONSTRAINT fk_history_points_user_id FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT check_history_points_earned CHECK (points_earned >= 0),
    CONSTRAINT uq_history_points_action_user_date UNIQUE (action_id, user_id, date)
);
