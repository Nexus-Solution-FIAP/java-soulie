-- Fecha as três falhas críticas que a auditoria encontrou no código portado.
--
-- 1. Papel administrativo: `POST /action` escrevia no catálogo global de ações,
--    com valor de pontos arbitrário, para qualquer usuário autenticado. O
--    @EnableMethodSecurity já estava ligado, mas getAuthorities() devolvia
--    ROLE_USER fixo — não havia papel para exigir.
-- 2. Catálogo de recompensas: `POST /reward` recebia o texto do benefício E o
--    preço no corpo da requisição. Dava para resgatar qualquer coisa por 1 ponto.
-- 3. Guardas no banco contra corrida: o saldo podia ficar negativo e os pontos
--    de uma ação podiam causar overflow de int no XP.

-- ---------------------------------------------------------------------------
-- 1. Papel do usuário
-- ---------------------------------------------------------------------------
ALTER TABLE users
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'USER';

ALTER TABLE users
    ADD CONSTRAINT check_users_role CHECK (role IN ('USER', 'ADMIN'));

-- Não existe rota para promover alguém a ADMIN, de propósito: uma rota assim
-- seria o alvo óbvio de escalonamento de privilégio. O primeiro administrador
-- é promovido direto no banco:
--     UPDATE users SET role = 'ADMIN' WHERE email = 'voce@exemplo.com';

-- ---------------------------------------------------------------------------
-- 2. Guardas de integridade que faltavam
-- ---------------------------------------------------------------------------

-- O saldo nunca pode ficar negativo. A checagem na entidade só protege dentro
-- de uma transação; esta é a rede que pega corrida entre duas.
ALTER TABLE users
    ADD CONSTRAINT check_users_points CHECK (points >= 0);

-- Teto nos pontos de uma ação. Sem isto, `points = 2000000000` causava overflow
-- de int em User.addPoints e Avatar.addXp quando a missão fosse concluída,
-- virando o saldo negativo e corrompendo o ranking.
ALTER TABLE actions
    ADD CONSTRAINT check_actions_points CHECK (points BETWEEN 1 AND 1000);

-- ---------------------------------------------------------------------------
-- 3. Catálogo de recompensas
-- ---------------------------------------------------------------------------
CREATE TABLE reward_catalog
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    benefits    VARCHAR(500) NOT NULL,
    cost        INTEGER      NOT NULL,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT check_reward_catalog_cost CHECK (cost > 0)
);

CREATE INDEX idx_reward_catalog_active ON reward_catalog (active);

-- O resgate passa a apontar para o item do catálogo. Fica nulo nas linhas
-- antigas, que foram criadas quando o preço vinha do cliente — elas são
-- mantidas como histórico, não apagadas.
ALTER TABLE rewards
    ADD COLUMN reward_catalog_id BIGINT;

ALTER TABLE rewards
    ADD CONSTRAINT fk_rewards_catalog_id
        FOREIGN KEY (reward_catalog_id) REFERENCES reward_catalog (id);

CREATE INDEX idx_rewards_user_id ON rewards (user_id);

